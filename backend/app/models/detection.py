"""
backend/app/models/detection.py
SQLAlchemy ORM models for ML anomaly detections and multi-class attack classifications.
"""
import uuid
from datetime import datetime
from typing import Any, Optional

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Index, JSON, String, Uuid
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


class Detection(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Anomaly detection output generated by unsupervised or binary classification models.
    """

    __tablename__ = "detections"

    host_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("hosts.id", ondelete="CASCADE"),
        nullable=False,
    )
    ts: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    anomaly_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    is_attack: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, index=True)
    model_id: Mapped[Optional[uuid.UUID]] = mapped_column(Uuid(as_uuid=True), nullable=True, index=True)
    status: Mapped[str] = mapped_column(String(32), nullable=False, default="open", index=True)

    __table_args__ = (
        Index("ix_detections_host_id_ts", "host_id", "ts"),
    )

    def __repr__(self) -> str:
        return f"<Detection id={self.id} host_id={self.host_id} is_attack={self.is_attack} score={self.anomaly_score:.2f}>"


class Classification(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Multi-class threat classification (e.g. brute_force, ddos, port_scan, etc.).
    """

    __tablename__ = "classifications"

    host_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("hosts.id", ondelete="CASCADE"),
        nullable=False,
    )
    ts: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )
    detection_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("detections.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    label: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    confidence: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    probs: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    model_id: Mapped[Optional[uuid.UUID]] = mapped_column(Uuid(as_uuid=True), nullable=True, index=True)

    __table_args__ = (
        Index("ix_classifications_host_id_ts", "host_id", "ts"),
    )

    def __repr__(self) -> str:
        return f"<Classification id={self.id} label={self.label} conf={self.confidence:.2f}>"

